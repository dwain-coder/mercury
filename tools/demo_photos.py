"""Demo-only hotel photography.

The property's own photographs are not licensed to this site. For Jon's preview we want the
page to look like a finished site, so the old site's images are pulled from the domain he now
owns, resized, and **stamped** with a banner saying what they are. The stamp is burned into
the pixels so it survives a screenshot, and the pages that use them carry `demo = true`, which
the release gate refuses to build. Replace them with a licensed feed before launch.

    python tools/demo_photos.py          -> assets/img/demo/*.webp (+ -700) and the TOML block
"""

from __future__ import annotations

