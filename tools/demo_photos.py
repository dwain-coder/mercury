def font(size: int, weight: int = 600) -> ImageFont.FreeTypeFont:
    f = ImageFont.truetype(str(FONTS / "NotoSansJP-VF.ttf"), size)
    try:
        f.set_variation_by_axes([weight])
    except Exception:
        pass
    return f


def stamp(im: Image.Image) -> Image.Image:
    """A banner across the bottom, sized to the image so both widths read the same."""
    im = im.convert("RGB")
    w, h = im.size
    bar = max(30, round(h * 0.085))
    strip = Image.new("RGBA", (w, bar), (24, 27, 39, 235))
    d = ImageDraw.Draw(strip)
    f1, f2 = font(round(bar * 0.36)), font(round(bar * 0.26), 500)
    # Centred, because the page crops these images to a fixed ratio and would clip a
    # left-aligned banner's first characters.
    d.text((w / 2 - f1.getlength(BANNER_JA) / 2, bar * 0.14), BANNER_JA, font=f1, fill=(255, 255, 255))
    d.text((w / 2 - f2.getlength(BANNER_EN) / 2, bar * 0.58), BANNER_EN, font=f2, fill=(214, 172, 164))
    im.paste(strip, (0, h - bar), strip)
    return im


def emit(path: Path, key: str, alt: str, caption: str) -> str:
    im = Image.open(path)
    im.load()
    out = []
    for width in (1400, 700):
        v = im.copy()
        v.thumbnail((width, width * 2), Image.LANCZOS)
        v = stamp(v)
        name = f"{key}.webp" if width == 1400 else f"{key}-700.webp"
        v.save(OUT / name, "WEBP", quality=74, method=5)
        out.append(v.size)
    w, h = out[0]
    return f"""[{key}]
src = "/assets/img/demo/{key}.webp"
alt = "{alt}"
caption = "{caption}"
credit = "画像：旧hotelmercury.jpの掲載画像（デモ用・差し替え前提）"
licence = "未許諾（デモ表示のみ）"
licence_url = ""
source = "https://hotelmercury.jp/"
origin = "旧サイト"
demo = true
width = {w}
height = {h}
"""


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    blocks = []
    for fn, key, alt, caption in PHOTOS:
        p = SRC / fn
        if not p.exists():
            sys.exit(f"missing {p} — run the capture first")
        blocks.append(emit(p, key, alt, caption))
    (ROOT / "content" / "photos-demo.toml").write_text(
        "# GENERATED by tools/demo_photos.py — scraped, stamped, demo only. Do not release.\n"
        "# Delete this file and its entries when licensed photography is wired in.\n\n"
        + "\n".join(blocks), encoding="utf-8")
    print(f"{len(blocks)} demo photos -> {OUT} + content/photos-demo.toml")


if __name__ == "__main__":
    main()
